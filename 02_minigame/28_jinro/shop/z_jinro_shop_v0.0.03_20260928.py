SHOP_DISTANCE = 5


# ============================================================
# 村人検索
# ============================================================

def villager_selector(tag):
    return (
        f'@e[type=villager,tag={tag},'
        f'distance=..{SHOP_DISTANCE},'
        f'sort=nearest,limit=1]'
    )


# ============================================================
# 取引追加
# ============================================================

def add_trade(tag, buy_item, buy_count, sell_item, sell_count):

    selector = villager_selector(tag)

    m.execute(
        f'/data modify entity {selector} '
        f'Offers.Recipes append value '
        f'{{buy:{{id:"{buy_item}",count:{buy_count}}},'
        f'sell:{{id:"{sell_item}",count:{sell_count}}},'
        f'maxUses:1000}}'
    )


# ============================================================
# 商品名
# ============================================================

def set_name(tag, trade_index, name):

    selector = villager_selector(tag)

    m.execute(
        f'/data modify entity {selector} '
        f'Offers.Recipes[{trade_index}].sell.components."minecraft:custom_name" '
        f'set value "{name}"'
    )


# ============================================================
# Lore
# ============================================================

def add_lore(tag, trade_index, text):

    selector = villager_selector(tag)

    m.execute(
        f'/data modify entity {selector} '
        f'Offers.Recipes[{trade_index}].sell.components."minecraft:lore" '
        f'append value "{text}"'
    )


# ============================================================
# 内部ID
#
# custom_data
#
# jinro_item = 英語ID
#
# SkriptではこのIDを使って
# アイテムの種類を判定する予定
# ============================================================

def set_item_id(tag, trade_index, item_id):

    selector = villager_selector(tag)

    m.execute(
        f'/data modify entity {selector} '
        f'Offers.Recipes[{trade_index}].sell.components."minecraft:custom_data".jinro_item '
        f'set value "{item_id}"'
    )


# ============================================================
# 商品作成
#
# add_shop_item()
#
# 1回の呼び出しで
#
#   取引追加
#   ↓
#   名前設定
#   ↓
#   Lore設定
#   ↓
#   内部ID設定
#
# ============================================================

def add_shop_item(
    tag,
    trade_index,
    buy_count,
    item,
    item_count,
    name,
    lore_lines,
    item_id
):

    # 取引追加
    add_trade(
        tag,
        "emerald",
        buy_count,
        item,
        item_count
    )

    # 正式名称
    set_name(
        tag,
        trade_index,
        name
    )

    # Lore
    for line in lore_lines:
        add_lore(
            tag,
            trade_index,
            line
        )

    # 内部ID
    set_item_id(
        tag,
        trade_index,
        item_id
    )


