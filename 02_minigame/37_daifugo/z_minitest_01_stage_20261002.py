import minescript as m
import math
import random


# ============================================================
# SETTINGS
# ============================================================

SIZE = 100

# 100 x 100
HALF = SIZE // 2

# 地形の最大高さ
MAX_HEIGHT = 28

# 地形の最低高さ
MIN_HEIGHT = 2

# 地形を作るブロック単位
# 2 = 2 x 2 で生成
CELL_SIZE = 2

# 木の数
TREE_COUNT = 45

# ランダムシード
RANDOM_SEED = 2602


# ============================================================
# BASE POSITION
# ============================================================

px, py, pz = m.player().position

BASE_X = math.floor(px)
BASE_Y = math.floor(py)
BASE_Z = math.floor(pz)


# ============================================================
# RANDOM
# ============================================================

random.seed(RANDOM_SEED)


# ============================================================
# AREA
# ============================================================

MIN_X = BASE_X - HALF
MAX_X = BASE_X + HALF - 1

MIN_Z = BASE_Z - HALF
MAX_Z = BASE_Z + HALF - 1


# ============================================================
# JUNGLE AREA
#
# ステージの左側をジャングルにする
# ============================================================

JUNGLE_MIN_X = MIN_X
JUNGLE_MAX_X = BASE_X - 5

JUNGLE_MIN_Z = MIN_Z
JUNGLE_MAX_Z = MAX_Z


# ============================================================
# HEIGHT FUNCTION
#
# 山・谷・ランダムな凹凸を作る
# ============================================================

def terrain_height(x, z):

    # --------------------------------------------------------
    # 基本高さ
    # --------------------------------------------------------

    height = 7


    # --------------------------------------------------------
    # 山 1
    # --------------------------------------------------------

    dx = x - (BASE_X + 25)
    dz = z - (BASE_Z - 15)

    distance = math.sqrt(
        dx * dx +
        dz * dz
    )

    mountain1 = max(
        0,
        25 - distance
    )

    height += mountain1 * 0.65


    # --------------------------------------------------------
    # 山 2
    # --------------------------------------------------------

    dx = x - (BASE_X + 5)
    dz = z - (BASE_Z + 28)

    distance = math.sqrt(
        dx * dx +
        dz * dz
    )

    mountain2 = max(
        0,
        18 - distance
    )

    height += mountain2 * 0.75


    # --------------------------------------------------------
    # 谷
    # --------------------------------------------------------

    dx = x - (BASE_X - 18)
    dz = z - (BASE_Z + 5)

    distance = math.sqrt(
        dx * dx +
        dz * dz
    )

    valley = max(
        0,
        18 - distance
    )

    height -= valley * 0.45


    # --------------------------------------------------------
    # 不規則な凹凸
    # --------------------------------------------------------

    height += (
        math.sin(x * 0.19)
        * math.cos(z * 0.17)
        * 3
    )

    height += (
        math.sin(
            (x + z) * 0.07
        )
        * 2
    )


    # --------------------------------------------------------
    # ランダム要素
    # --------------------------------------------------------

    random.seed(
        RANDOM_SEED
        + x * 7919
        + z * 104729
    )

    height += random.randint(
        -2,
        2
    )


    # --------------------------------------------------------
    # LIMIT
    # --------------------------------------------------------

    height = max(
        MIN_HEIGHT,
        height
    )

    height = min(
        MAX_HEIGHT,
        height
    )


    return BASE_Y + int(height)


# ============================================================
# JUNGLE CHECK
# ============================================================

def is_jungle(x, z):

    return (
        JUNGLE_MIN_X <= x <= JUNGLE_MAX_X
        and
        JUNGLE_MIN_Z <= z <= JUNGLE_MAX_Z
    )


# ============================================================
# CLEAR AREA
# ============================================================

def clear_area():

    m.echo(
        "[STAGE] Clearing area..."
    )

    m.execute(
        f"fill "
        f"{MIN_X} {BASE_Y + 1} {MIN_Z} "
        f"{MAX_X} {BASE_Y + MAX_HEIGHT + 35} {MAX_Z} "
        f"air"
    )


# ============================================================
# GENERATE TERRAIN
# ============================================================

def generate_terrain():

    m.echo(
        "[STAGE] Generating terrain..."
    )

    count = 0

    for x in range(
        MIN_X,
        MAX_X + 1,
        CELL_SIZE
    ):

        for z in range(
            MIN_Z,
            MAX_Z + 1,
            CELL_SIZE
        ):

            # 中央座標
            center_x = (
                x +
                CELL_SIZE // 2
            )

            center_z = (
                z +
                CELL_SIZE // 2
            )

            height = terrain_height(
                center_x,
                center_z
            )

            # ------------------------------------------------
            # 地面
            # ------------------------------------------------

            ground_height = (
                height - BASE_Y
            )

            # 石
            if ground_height > 4:

                m.execute(
                    f"fill "
                    f"{x} {BASE_Y} {z} "
                    f"{min(x + CELL_SIZE - 1, MAX_X)} "
                    f"{height - 3} "
                    f"{min(z + CELL_SIZE - 1, MAX_Z)} "
                    f"stone"
                )

            # 土
            if ground_height >= 3:

                dirt_bottom = max(
                    BASE_Y,
                    height - 3
                )

                m.execute(
                    f"fill "
                    f"{x} {dirt_bottom} {z} "
                    f"{min(x + CELL_SIZE - 1, MAX_X)} "
                    f"{height - 1} "
                    f"{min(z + CELL_SIZE - 1, MAX_Z)} "
                    f"dirt"
                )

            # 草
            m.execute(
                f"fill "
                f"{x} {height} {z} "
                f"{min(x + CELL_SIZE - 1, MAX_X)} "
                f"{height} "
                f"{min(z + CELL_SIZE - 1, MAX_Z)} "
                f"grass_block"
            )

            count += 1

        if count % 500 == 0:

            m.echo(
                f"[STAGE] Terrain: {count} cells"
            )


# ============================================================
# GENERATE JUNGLE FLOOR
# ============================================================

def generate_jungle_floor():

    m.echo(
        "[STAGE] Creating jungle..."
    )

    # ジャングル側に草ブロックを追加
    #
    # 地形そのものは通常のterrain生成で作るため、
    # ここでは木を生やす場所を作るだけ。


# ============================================================
# TREE
# ============================================================

def create_tree(x, y, z):

    # --------------------------------------------------------
    # 幹の高さ
    # --------------------------------------------------------

    height = random.randint(
        4,
        7
    )


    # --------------------------------------------------------
    # 幹
    # --------------------------------------------------------

    m.execute(
        f"fill "
        f"{x} {y + 1} {z} "
        f"{x} {y + height} {z} "
        f"jungle_log"
    )


    # --------------------------------------------------------
    # 葉
    # --------------------------------------------------------

    leaf_y = y + height


    # 上部
    m.execute(
        f"fill "
        f"{x - 2} {leaf_y - 1} {z - 2} "
        f"{x + 2} {leaf_y + 1} {z + 2} "
        f"jungle_leaves"
    )


    # 中央上部
    m.execute(
        f"fill "
        f"{x - 1} {leaf_y + 2} {z - 1} "
        f"{x + 1} {leaf_y + 2} {z + 1} "
        f"jungle_leaves"
    )


    # --------------------------------------------------------
    # 葉の外側を少し削る
    #
    # 完全な四角形にしない
    # --------------------------------------------------------

    m.execute(
        f"setblock "
        f"{x - 2} {leaf_y + 1} {z - 2} "
        f"air"
    )

    m.execute(
        f"setblock "
        f"{x + 2} {leaf_y + 1} {z + 2} "
        f"air"
    )

    m.execute(
        f"setblock "
        f"{x - 2} {leaf_y + 1} {z + 2} "
        f"air"
    )

    m.execute(
        f"setblock "
        f"{x + 2} {leaf_y + 1} {z - 2} "
        f"air"
    )


# ============================================================
# GENERATE TREES
# ============================================================

def generate_trees():

    m.echo(
        "[STAGE] Planting trees..."
    )

    created = 0

    attempts = 0

    max_attempts = TREE_COUNT * 10


    while (
        created < TREE_COUNT
        and attempts < max_attempts
    ):

        attempts += 1


        # ----------------------------------------------------
        # ジャングル範囲からランダム取得
        # ----------------------------------------------------

        x = random.randint(
            JUNGLE_MIN_X + 3,
            JUNGLE_MAX_X - 3
        )

        z = random.randint(
            JUNGLE_MIN_Z + 3,
            JUNGLE_MAX_Z - 3
        )


        # ----------------------------------------------------
        # 高さ
        # ----------------------------------------------------

        y = terrain_height(
            x,
            z
        )


        # ----------------------------------------------------
        # 木が高すぎる山の上に出ないようにする
        # ----------------------------------------------------

        if y > BASE_Y + 18:

            continue


        # ----------------------------------------------------
        # 木
        # ----------------------------------------------------

        create_tree(
            x,
            y,
            z
        )

        created += 1


        if created % 10 == 0:

            m.echo(
                f"[STAGE] Trees: {created}/{TREE_COUNT}"
            )


# ============================================================
# EXTRA ROCKS
# ============================================================

def generate_rocks():

    m.echo(
        "[STAGE] Adding rocks..."
    )

    for i in range(35):

        x = random.randint(
            MIN_X,
            MAX_X
        )

        z = random.randint(
            MIN_Z,
            MAX_Z
        )

        y = terrain_height(
            x,
            z
        )

        # 小さな石
        m.execute(
            f"setblock "
            f"{x} {y + 1} {z} "
            f"cobblestone"
        )

        # たまに2個
        if random.randint(0, 2) == 0:

            m.execute(
                f"setblock "
                f"{x + 1} {y + 1} {z} "
                f"cobblestone"
            )


# ============================================================
# START
# ============================================================

def main():

    m.echo(
        "================================"
    )

    m.echo(
        "[STAGE] Stage generation START"
    )

    m.echo(
        f"[STAGE] Center: "
        f"{BASE_X} {BASE_Y} {BASE_Z}"
    )

    m.echo(
        "[STAGE] Size: 100 x 100"
    )

    m.echo(
        "================================"
    )


    # --------------------------------------------------------
    # クリエイティブ
    # --------------------------------------------------------

    m.execute(
        "gamemode creative @s"
    )


    # --------------------------------------------------------
    # プレイヤー退避
    #
    # 現在地の60ブロック上
    # --------------------------------------------------------

    m.execute(
        f"tp @s "
        f"{BASE_X} "
        f"{BASE_Y + 60} "
        f"{BASE_Z}"
    )


    # --------------------------------------------------------
    # エリアクリア
    # --------------------------------------------------------

    clear_area()


    # --------------------------------------------------------
    # 地形
    # --------------------------------------------------------

    generate_terrain()


    # --------------------------------------------------------
    # ジャングル
    # --------------------------------------------------------

    generate_jungle_floor()


    # --------------------------------------------------------
    # 木
    # --------------------------------------------------------

    generate_trees()


    # --------------------------------------------------------
    # 岩
    # --------------------------------------------------------

    generate_rocks()


    # --------------------------------------------------------
    # 最終位置
    #
    # 中央上空へ
    # --------------------------------------------------------

    final_y = (
        BASE_Y +
        MAX_HEIGHT +
        10
    )

    m.execute(
        f"tp @s "
        f"{BASE_X} "
        f"{final_y} "
        f"{BASE_Z}"
    )


    m.echo(
        "================================"
    )

    m.echo(
        "[STAGE] Stage generation COMPLETE"
    )

    m.echo(
        "[STAGE] Mountain + Valley + Jungle + Trees"
    )

    m.echo(
        "================================"
    )


# ============================================================
# RUN
# ============================================================

main()